<?php

namespace App\Services\Sms;

class SmsUserMessage
{
    public static function forResult(SmsResult $result): string
    {
        if ($result->status === SmsStatus::Unknown) {
            return 'გაგზავნის შედეგი ვერ დადგინდა. თუ კოდი მოგივიდათ, გამოიყენეთ იგი. ხელახლა ავტომატურად არ იგზავნება.';
        }

        return match ($result->errorCode) {
            20 => 'SMS ბალანსი არასაკმარისია. სცადეთ მოგვიანებით.',
            10, 70, 76, 77 => 'ნომრის ფორმატი არასწორია. შეიყვანეთ ქართული მობილური ნომერი.',
            -100 => 'SMS სერვისი დროებით მიუწვდომელია. სცადეთ ცოტა ხანში.',
            40 => 'შეტყობინების ტექსტი ძალიან გრძელია.',
            80, 110, 120, 150, 500, 600, 700, 800 => 'SMS სერვისი არ არის გამართული. დაუკავშირდით ადმინისტრატორს.',
            default => $result->reason === 'missing_key' || $result->reason === 'sender'
                ? 'SMS სერვისი არ არის გამართული. დაუკავშირდით ადმინისტრატორს.'
                : 'შეტყობინება ვერ გაიგზავნა. სცადეთ ცოტა ხანში.',
        };
    }
}
